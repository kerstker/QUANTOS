"""Pure review of feedback upgrade materials; no installation or authority.

The caller supplies explicit preimages for all four targets. These are claims
until a protected installer captures and rechecks actual filesystem custody.
This module neither reads production paths nor authorizes service activation.
"""
import hashlib

from scripts.render_demo_feedback_units import render
from services.governance.json_integrity import load_json_without_duplicate_keys
from tools.demo_feedback_publish import validate_configuration


TARGETS = {
    'quantos-demo-feedback.service': '/etc/systemd/system/quantos-demo-feedback.service',
    'quantos-demo-feedback.timer': '/etc/systemd/system/quantos-demo-feedback.timer',
    'feedback-automation.json': '/etc/quantos/demo-observation/feedback-automation.json',
    'research-feedback.json': '/etc/quantos/demo-observation/research-feedback.json',
}
MAXIMUM = 65536


def _require(condition, reason):
    if not condition:
        raise ValueError(reason)


def _hash(body):
    return hashlib.sha256(body).hexdigest()


def _preimages(preimages):
    _require(type(preimages) is dict and set(preimages) == set(TARGETS),
             'FEEDBACK_UPGRADE_PREIMAGES')
    _require(all(body is None or (type(body) is bytes and len(body) <= MAXIMUM)
                 for body in preimages.values()), 'FEEDBACK_UPGRADE_PREIMAGES')
    return {name: None if body is None else _hash(body)
            for name, body in preimages.items()}


def review(*, files, preimages, release_commit):
    """Bind exact generated bytes and explicit old bytes/absence, without I/O."""
    _require(type(files) is dict and set(files) == set(TARGETS), 'FEEDBACK_UPGRADE_FILES')
    _require(all(type(body) is bytes and 0 < len(body) <= MAXIMUM for body in files.values()),
             'FEEDBACK_UPGRADE_FILES')
    before = _preimages(preimages)
    cfg = validate_configuration(load_json_without_duplicate_keys(files['research-feedback.json']),
                                 source_commit=release_commit)
    expected = render(release_commit=release_commit, research_state_root=cfg['research_state_root'],
                      executor_uid=cfg['executor_uid'], research_uid=cfg['research_uid'],
                      research_gid=cfg['research_gid'])
    _require(files == {name: body.encode() for name, body in expected.items()},
             'FEEDBACK_UPGRADE_MATERIAL_MISMATCH')
    return {
        'schema': 'DEMO_FEEDBACK_UPGRADE_REVIEW_V1',
        'release_commit': release_commit,
        'targets': {name: {'path': path, 'before_sha256': before[name],
                           'after_sha256': _hash(files[name])}
                    for name, path in TARGETS.items()},
        'publication': dict(cfg),
        'preimages_verified': False,
        'activation_authorized': False,
        'installed': False,
    }


def recheck(value, *, files, preimages):
    """Reject stale preimages or modified review/materials before any mutation."""
    _require(type(value) is dict and type(value.get('targets')) is dict
             and set(value['targets']) == set(TARGETS), 'FEEDBACK_UPGRADE_REVIEW')
    current = _preimages(preimages)
    _require(all(type(row) is dict and row.get('before_sha256') == current[name]
                 for name, row in value['targets'].items()), 'FEEDBACK_UPGRADE_PREIMAGE_CHANGED')
    expected = review(files=files, preimages=preimages, release_commit=value.get('release_commit'))
    _require(value == expected, 'FEEDBACK_UPGRADE_REVIEW_CHANGED')
    return expected
