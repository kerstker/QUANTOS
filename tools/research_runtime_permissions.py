"""Repair access modes of a verified research venv; never follow links or change source."""

import hashlib
import json
from pathlib import Path
import stat


def protected_parents(root, owner):
    for parent in (root, *root.parents):
        info = parent.lstat()
        if not stat.S_ISDIR(info.st_mode) or info.st_uid != owner or info.st_mode & 0o022:
            raise ValueError("RUNTIME_PARENT_CUSTODY")


def repair(root, binding, *, owner=0):
    root = Path(root)
    protected_parents(root, owner)
    receipt = root / "quantos-maintenance-install.json"
    info = receipt.lstat()
    if not stat.S_ISREG(info.st_mode) or info.st_uid != owner or info.st_nlink != 1 or info.st_mode & 0o022:
        raise ValueError("RUNTIME_RECEIPT_CUSTODY")
    stamp = hashlib.sha256(json.dumps(binding, sort_keys=True).encode()).hexdigest()
    if json.loads(receipt.read_bytes()) != {"binding_sha256": stamp}:
        raise ValueError("RUNTIME_RECEIPT_BINDING")
    allowed = {
        "bin",
        "include",
        "lib",
        "lib64",
        "pyvenv.cfg",
        "quantos-maintenance",
        "quantos-maintenance-install.json",
    }
    if not {p.name for p in root.iterdir()} <= allowed:
        raise ValueError("RUNTIME_LAYOUT")
    rows = [(root, 0o755)]
    pending = [p for p in root.iterdir() if p.name != "quantos-maintenance"]
    while pending:
        path = pending.pop()
        info = path.lstat()
        if info.st_uid != owner:
            raise ValueError("RUNTIME_OWNER")
        if stat.S_ISLNK(info.st_mode):
            target = path.resolve(strict=True)
            if not target.is_relative_to(root) and target != Path("/usr/bin/python3.12").resolve():
                raise ValueError("RUNTIME_LINK")
            continue
        if info.st_mode & 0o022 or info.st_mode & 0o7000:
            raise ValueError("RUNTIME_MODE")
        if stat.S_ISDIR(info.st_mode):
            rows.append((path, 0o755))
            pending.extend(path.iterdir())
        elif stat.S_ISREG(info.st_mode) and info.st_nlink == 1:
            rows.append((path, 0o755 if info.st_mode & 0o111 else 0o644))
        else:
            raise ValueError("RUNTIME_FILE_TYPE")
        if len(rows) + len(pending) > 200000:
            raise ValueError("RUNTIME_SIZE")
    # Validate the whole scope first. Parents are owner-controlled and not
    # writable by other users; symlinks are excluded from all mutations.
    changed = 0
    for path, mode in reversed(rows):
        if stat.S_IMODE(path.lstat().st_mode) != mode:
            path.chmod(mode, follow_symlinks=False)
            changed += 1
    return {"status": "RUNTIME_ACCESS_REPAIRED", "changed_paths": changed, "services_changed": False}


def repair_release_metadata(root, *, owner=0):
    """Make only Git index and generated bytecode readable; keep source bytes intact."""
    root = Path(root)
    protected_parents(root, owner)
    paths = [root / ".git" / "index"]
    for path in root.rglob("*"):
        if "__pycache__" in path.relative_to(root).parts:
            paths.append(path)
        if len(paths) > 200000:
            raise ValueError("RELEASE_METADATA_SIZE")
    rows = []
    for path in paths:
        info = path.lstat()
        if info.st_uid != owner or info.st_mode & 0o7022:
            raise ValueError("RELEASE_METADATA_CUSTODY")
        if stat.S_ISDIR(info.st_mode):
            rows.append((path, 0o755))
        elif stat.S_ISREG(info.st_mode) and info.st_nlink == 1:
            if path != root / ".git" / "index" and path.suffix != ".pyc":
                raise ValueError("RELEASE_METADATA_TYPE")
            rows.append((path, 0o644))
        else:
            raise ValueError("RELEASE_METADATA_TYPE")
    changed = 0
    for path, mode in reversed(rows):
        if stat.S_IMODE(path.lstat().st_mode) != mode:
            path.chmod(mode, follow_symlinks=False)
            changed += 1
    return {"status": "RELEASE_METADATA_ACCESS_REPAIRED", "changed_paths": changed, "source_bytes_changed": False}
