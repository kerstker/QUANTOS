"""Pure contracts for CI dependency locking and coverage regression floors."""

from __future__ import annotations

from dataclasses import dataclass
import json
import math
import re
from typing import Any, Iterable, Mapping, Sequence
from urllib.parse import urlsplit


_SHA256 = re.compile(r"^[0-9a-f]{64}$")
_PACKAGE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$")
_VERSION = re.compile(r"^[0-9][0-9A-Za-z.!+_-]*$")
_TARGET = re.compile(r"^[A-Za-z0-9_.-]+$")
_LOCK_HEADER = "# QUANTOS CI DEPENDENCY LOCK v1"
_SOURCE_PREFIX = "# source-sha256: "
_PYTHON_PREFIX = "# python-version: "
_PLATFORM_PREFIX = "# platform-tag: "
_PACKAGE_PREFIX = "# package: "
_LOCK_LINE = re.compile(
    r"^(?P<name>[A-Za-z0-9][A-Za-z0-9_.-]*) @ "
    r"(?P<url>https://\S+) --hash=sha256:(?P<sha>[0-9a-f]{64})$"
)


class CiReproducibilityError(ValueError):
    """Raised when a CI reproducibility contract cannot be verified."""


@dataclass(frozen=True)
class VerifiedLock:
    package_count: int
    package_names: tuple[str, ...]
    python_version: str
    platform_tag: str


@dataclass(frozen=True)
class CoverageResult:
    line_percent: float
    branch_percent: float


def _canonical_package(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _require_sha256(value: Any, *, label: str) -> str:
    if not isinstance(value, str) or _SHA256.fullmatch(value) is None:
        raise CiReproducibilityError(f"{label} must be a lowercase sha256 digest")
    return value


def _require_target(value: Any, *, label: str) -> str:
    if not isinstance(value, str) or _TARGET.fullmatch(value) is None:
        raise CiReproducibilityError(f"{label} is invalid")
    return value


def _locked_rows(report: Mapping[str, Any]) -> list[tuple[str, str, str, str]]:
    install = report.get("install")
    if not isinstance(install, list) or not install:
        raise CiReproducibilityError("pip report install set must be a non-empty list")
    rows: list[tuple[str, str, str, str]] = []
    seen: set[str] = set()
    for item in install:
        if not isinstance(item, Mapping):
            raise CiReproducibilityError("pip report install item must be an object")
        metadata = item.get("metadata")
        download = item.get("download_info")
        if not isinstance(metadata, Mapping) or not isinstance(download, Mapping):
            raise CiReproducibilityError("pip report item lacks metadata or download_info")
        name = metadata.get("name")
        version = metadata.get("version")
        if not isinstance(name, str) or _PACKAGE.fullmatch(name) is None:
            raise CiReproducibilityError("package name is invalid")
        if not isinstance(version, str) or _VERSION.fullmatch(version) is None:
            raise CiReproducibilityError(f"package {name} version is not exact")
        canonical = _canonical_package(name)
        if canonical in seen:
            raise CiReproducibilityError(f"duplicate package in lock: {canonical}")
        seen.add(canonical)
        url = download.get("url")
        if not isinstance(url, str):
            raise CiReproducibilityError(f"package {name} artifact URL is missing")
        parsed = urlsplit(url)
        if (
            parsed.scheme != "https"
            or parsed.hostname != "files.pythonhosted.org"
            or parsed.username is not None
            or parsed.password is not None
        ):
            raise CiReproducibilityError(
                f"package {name} artifact must use credential-free HTTPS from files.pythonhosted.org"
            )
        archive = download.get("archive_info")
        hashes = archive.get("hashes") if isinstance(archive, Mapping) else None
        sha256 = hashes.get("sha256") if isinstance(hashes, Mapping) else None
        digest = _require_sha256(sha256, label=f"package {name} sha256")
        rows.append((canonical, version, url, digest))
    rows.sort(key=lambda row: row[0])
    return rows


def build_lock_document(
    report: Mapping[str, Any],
    *,
    source_hashes: Mapping[str, str],
    python_version: str,
    platform_tag: str,
) -> str:
    """Build a pip-installable, direct-artifact, hash-locked document."""
    py_target = _require_target(python_version, label="Python target")
    platform = _require_target(platform_tag, label="platform target")
    if not source_hashes:
        raise CiReproducibilityError("source requirement digests are required")
    sources: list[tuple[str, str]] = []
    for path, digest in source_hashes.items():
        if not isinstance(path, str) or not path or any(char in path for char in "\r\n="):
            raise CiReproducibilityError("source requirement path is invalid")
        sources.append((path, _require_sha256(digest, label=f"source {path} sha256")))
    sources.sort()

    lines = [
        _LOCK_HEADER,
        "# Generated by scripts/generate_ci_dependency_lock.py; do not edit by hand.",
        f"{_PYTHON_PREFIX}{py_target}",
        f"{_PLATFORM_PREFIX}{platform}",
    ]
    lines.extend(f"{_SOURCE_PREFIX}{path}={digest}" for path, digest in sources)
    lines.append("")
    for name, version, url, digest in _locked_rows(report):
        lines.append(f"{_PACKAGE_PREFIX}{name}=={version}")
        lines.append(f"{name} @ {url} --hash=sha256:{digest}")
    return "\n".join(lines) + "\n"


def verify_lock_document(
    document: str,
    *,
    expected_source_hashes: Mapping[str, str],
    required_python_version: str,
    required_platform_tag: str,
) -> VerifiedLock:
    if not isinstance(document, str) or not document.endswith("\n"):
        raise CiReproducibilityError("lock document must be newline terminated")
    lines = document.splitlines()
    if not lines or lines[0] != _LOCK_HEADER:
        raise CiReproducibilityError("lock document header is invalid")
    python_rows = [line.removeprefix(_PYTHON_PREFIX) for line in lines if line.startswith(_PYTHON_PREFIX)]
    platform_rows = [line.removeprefix(_PLATFORM_PREFIX) for line in lines if line.startswith(_PLATFORM_PREFIX)]
    if python_rows != [required_python_version]:
        raise CiReproducibilityError("Python target does not match the CI policy")
    if platform_rows != [required_platform_tag]:
        raise CiReproducibilityError("platform target does not match the CI policy")

    observed_sources: dict[str, str] = {}
    for line in lines:
        if not line.startswith(_SOURCE_PREFIX):
            continue
        payload = line.removeprefix(_SOURCE_PREFIX)
        if "=" not in payload:
            raise CiReproducibilityError("source requirement digest row is malformed")
        path, digest = payload.rsplit("=", 1)
        if path in observed_sources:
            raise CiReproducibilityError("source requirement digest is duplicated")
        observed_sources[path] = _require_sha256(digest, label=f"source {path} sha256")
    expected = {
        path: _require_sha256(digest, label=f"source {path} sha256")
        for path, digest in expected_source_hashes.items()
    }
    if observed_sources != expected:
        raise CiReproducibilityError("source requirement digest mismatch")

    versions: dict[str, str] = {}
    packages: dict[str, tuple[str, str]] = {}
    pending: tuple[str, str] | None = None
    for line in lines:
        if line.startswith(_PACKAGE_PREFIX):
            if pending is not None:
                raise CiReproducibilityError("package metadata lacks a lock line")
            value = line.removeprefix(_PACKAGE_PREFIX)
            if "==" not in value:
                raise CiReproducibilityError("package version row is malformed")
            raw_name, version = value.rsplit("==", 1)
            name = _canonical_package(raw_name)
            if _PACKAGE.fullmatch(raw_name) is None or _VERSION.fullmatch(version) is None:
                raise CiReproducibilityError("package version row is invalid")
            pending = (name, version)
            continue
        match = _LOCK_LINE.fullmatch(line)
        if match is None:
            continue
        name = _canonical_package(match.group("name"))
        if pending is None or pending[0] != name:
            raise CiReproducibilityError("package lock line is not paired with its exact version")
        parsed = urlsplit(match.group("url"))
        if (
            parsed.scheme != "https"
            or parsed.hostname != "files.pythonhosted.org"
            or parsed.username
            or parsed.password
        ):
            raise CiReproducibilityError(
                "locked artifact must use credential-free HTTPS from files.pythonhosted.org"
            )
        if name in packages:
            raise CiReproducibilityError(f"duplicate package in lock: {name}")
        _require_sha256(match.group("sha"), label=f"package {name} sha256")
        versions[name] = pending[1]
        packages[name] = (match.group("url"), match.group("sha"))
        pending = None
    if pending is not None:
        raise CiReproducibilityError("package metadata lacks a lock line")
    if not packages:
        raise CiReproducibilityError("lock document contains no packages")
    return VerifiedLock(
        package_count=len(packages),
        package_names=tuple(sorted(packages)),
        python_version=required_python_version,
        platform_tag=required_platform_tag,
    )


def extract_backend_pytest_commands(
    checks: Iterable[tuple[str, Sequence[str], str]],
) -> tuple[tuple[str, ...], ...]:
    commands = tuple(
        tuple(str(item) for item in argv)
        for name, argv, _ in checks
        if name.startswith("pytest:")
    )
    if not commands:
        raise CiReproducibilityError("canonical validation exposes no backend pytest commands")
    for command in commands:
        if len(command) < 4 or command[1:3] != ("-m", "pytest"):
            raise CiReproducibilityError("canonical pytest command shape is unsupported")
    return commands


def _coverage_number(summary: Mapping[str, Any], key: str) -> int:
    value = summary.get(key)
    if isinstance(value, bool) or not isinstance(value, int) or value < 0:
        raise CiReproducibilityError(f"coverage summary {key} is invalid")
    return value


def _coverage_floor(value: Any, label: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise CiReproducibilityError(f"{label} coverage floor is invalid")
    result = float(value)
    if not math.isfinite(result) or not 0.0 < result <= 100.0:
        raise CiReproducibilityError(f"{label} coverage floor must be in (0, 100]")
    return result


def evaluate_coverage_summary(
    summary: Mapping[str, Any],
    *,
    minimum_line_percent: float,
    minimum_branch_percent: float,
) -> CoverageResult:
    covered_lines = _coverage_number(summary, "covered_lines")
    statements = _coverage_number(summary, "num_statements")
    covered_branches = _coverage_number(summary, "covered_branches")
    branches = _coverage_number(summary, "num_branches")
    if statements == 0 or branches == 0 or covered_lines > statements or covered_branches > branches:
        raise CiReproducibilityError("coverage summary has an empty or inconsistent denominator")
    line_percent = 100.0 * covered_lines / statements
    branch_percent = 100.0 * covered_branches / branches
    line_floor = _coverage_floor(minimum_line_percent, "line")
    branch_floor = _coverage_floor(minimum_branch_percent, "branch")
    if line_percent + 1e-12 < line_floor:
        raise CiReproducibilityError(
            f"line coverage {line_percent:.2f}% is below {line_floor:.2f}%"
        )
    if branch_percent + 1e-12 < branch_floor:
        raise CiReproducibilityError(
            f"branch coverage {branch_percent:.2f}% is below {branch_floor:.2f}%"
        )
    return CoverageResult(line_percent=line_percent, branch_percent=branch_percent)


def load_policy(path: str) -> Mapping[str, Any]:
    with open(path, "r", encoding="utf-8") as handle:
        document = json.load(handle)
    if not isinstance(document, Mapping):
        raise CiReproducibilityError("CI coverage policy must be an object")
    return document
