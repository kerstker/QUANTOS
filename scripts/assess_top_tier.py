#!/usr/bin/env python
"""Generate the offline QUANTOS top-tier assessment artifacts."""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path
from typing import Any, Sequence

REPO = Path(__file__).resolve().parents[1]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from scripts.evidence_binding import (  # noqa: E402
    assert_current_binding,
    resolve_canonical_source_anchor,
    validation_binding,
)
from services.governance.top_tier_assessment import (  # noqa: E402
    RegistryError,
    assess_repository,
)


DEFAULT_REGISTRY = REPO / "config" / "top_tier_requirements.json"
DEFAULT_JSON = REPO / "evidence" / "top_tier_assessment.json"
DEFAULT_MATRIX = REPO / "docs" / "QUANTOS_TOP_TIER_CAPABILITY_MATRIX.md"


def render_matrix(report: dict[str, Any]) -> str:
    summary = report["summary"]
    lines = [
        "# QUANTOS Top-Tier Capability Matrix", "",
        "> Generated by `python scripts/assess_top_tier.py`. Do not hand-edit maturity results.",
        "> L2_DRY_RUN_ONLY remains active; this matrix does not authorize live trading.", "",
        f"**System verdict:** `{report['verdict']}`", "",
        f"**Requirements:** {summary['total']} total; {summary['passed']} pass; "
        f"{summary['failed']} failed; {summary['manual_evidence_required']} manual/external; "
        f"{summary['red_lines_failed']} red lines open", "", "## Domain Summary", "",
        "| Domain | Maturity | Passed | Requirements | Red Lines Failed |",
        "|---|---:|---:|---:|---:|",
    ]
    for domain in report["domains"]:
        lines.append(f"| `{domain['domain']}` | {domain['current_maturity']} | {domain['passed']} | "
                     f"{domain['requirements']} | {domain['red_lines_failed']} |")
    lines.extend(["", "## Requirements", "",
                  "| Requirement | Domain | Tier | Class | Current / Target | Status | Red Line | Evidence | Gap / Next Action |",
                  "|---|---|---:|---|---|---|---:|---|---|"])
    for item in report["requirements"]:
        evidence = "<br>".join(f"`{path}`" for path in item["evidence"]) or "-"
        detail = _cell(item["detail"] + " Next: " + item["next_action"])
        lines.append(f"| `{item['id']}` | `{item['domain']}` | {item['tier']} | {item['classification']} | "
                     f"{item['current_maturity']} / {item['target_maturity']} | {item['status']} | "
                     f"{'YES' if item['red_line'] else 'NO'} | {evidence} | {detail} |")
    return "\n".join(lines) + "\n"


def _cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def write_artifacts(report: dict[str, Any], json_path: Path, matrix_path: Path) -> None:
    json_path.parent.mkdir(parents=True, exist_ok=True)
    matrix_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(json.dumps(report, ensure_ascii=False, sort_keys=True, indent=2) + "\n", encoding="utf-8")
    matrix_path.write_text(render_matrix(report), encoding="utf-8")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-root", default=str(REPO))
    parser.add_argument("--requirements", default=str(DEFAULT_REGISTRY))
    parser.add_argument("--json-out", default=str(DEFAULT_JSON))
    parser.add_argument("--matrix-out", default=str(DEFAULT_MATRIX))
    parser.add_argument("--as-of-ms", type=int)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        repo_root = Path(args.repo_root)
        canonical_source = resolve_canonical_source_anchor(repo_root)
        prior_generated_at = None
        prior_binding = None
        json_path = Path(args.json_out)
        if json_path.is_file():
            try:
                prior = json.loads(json_path.read_text(encoding="utf-8"))
                assert_current_binding(
                    prior,
                    head=canonical_source,
                    repo_root=repo_root,
                )
                prior_binding = prior["validation"]
                prior_generated_at = prior_binding["generated_at"]
            except (OSError, ValueError, TypeError, json.JSONDecodeError, KeyError):
                if args.check:
                    raise ValueError("existing assessment binding is not current")
        elif args.check:
            raise ValueError("assessment artifact is missing")
        as_of_ms = (
            args.as_of_ms
            if args.as_of_ms is not None
            else prior_generated_at
            if isinstance(prior_generated_at, int)
            else time.time_ns() // 1_000_000
        )
        report = assess_repository(
            repo_root,
            Path(args.requirements),
            as_of_ms=as_of_ms,
        )
        report["validation"] = (
            prior_binding
            if args.as_of_ms is None and prior_binding is not None
            else validation_binding(
                generated_at=as_of_ms,
                source_commit=canonical_source,
            )
        )
        json_path, matrix_path = Path(args.json_out), Path(args.matrix_out)
        if args.check:
            expected_json = json.dumps(report, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
            expected_matrix = render_matrix(report)
            if json_path.read_text(encoding="utf-8") != expected_json:
                print(f"assessment artifact drifted: {json_path}")
                return 1
            if matrix_path.read_text(encoding="utf-8") != expected_matrix:
                print(f"capability matrix drifted: {matrix_path}")
                return 1
        else:
            write_artifacts(report, json_path, matrix_path)
    except (OSError, RegistryError, ValueError) as exc:
        print(f"assessment failed: {exc}")
        return 1
    print(f"top-tier assessment: {report['verdict']} - {report['summary']['passed']}/{report['summary']['total']} pass")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
