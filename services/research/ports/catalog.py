"""Catalog capabilities consumed by research; implementation is injected."""
from __future__ import annotations
from collections.abc import Mapping, Sequence
from typing import Protocol
from quantos.contracts.alpha import AlphaDefinition
from services.lifecycle.catalog_snapshot import CatalogSnapshot


class CatalogPersistencePort(Protocol):
    def snapshot(self) -> CatalogSnapshot: ...
    def restore(self, snap: CatalogSnapshot) -> None: ...
    def sharpe(self, alpha_id: str) -> float | None: ...
    def restore_evaluation_context(self, *, trials: Sequence[str],
        historical_returns: Mapping[str, Sequence[float]],
        historical_pvalues: Mapping[str, float],
        historical_definition_hashes: Mapping[str, str] | None = None) -> None: ...


class ResearchCatalogPort(CatalogPersistencePort, Protocol):
    def register(self, definition: AlphaDefinition) -> None: ...
    def register_trial(self, config_hash: str) -> None: ...
    def get(self, alpha_id: str) -> AlphaDefinition: ...
    def all_ids(self) -> list[str]: ...
    def returns(self, alpha_id: str) -> tuple[float, ...]: ...
    def global_trial_count(self) -> int: ...
